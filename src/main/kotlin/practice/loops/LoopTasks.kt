/**
 * Задача 10 — Оптимизируй вложенные циклы
 *
 * Найди общие элементы двух списков.
 * Текущая реализация O(n^2). Оптимизируй до O(n).
 *
 * Подсказка: используй Set для быстрого поиска.
 */
fun task10() {
    val list1 = listOf(1, 3, 5, 7, 9, 11, 13)
    val list2 = listOf(2, 3, 7, 10, 11, 15)

    // Текущая реализация O(n^2) — перепиши:
    val common = mutableListOf<Int>()
    for (a in list1) {
        for (b in list2) {
            if (a == b) common.add(a)
        }
    }
    println("Общие элементы: $common")

    // Ожидаемый вывод:
    // Общие элементы: [3, 7, 11]
}


