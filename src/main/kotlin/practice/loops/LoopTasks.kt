/**
 * Задача 7 — Фильтрация логов
 *
 * Дан список лог-сообщений. Нужно:
 * - Пропустить (continue) сообщения уровня DEBUG
 * - Остановиться (break) при встрече FATAL
 * - Остальные — вывести
 */
fun task7() {
    val logs = listOf(
        "INFO: Сервер запущен",
        "DEBUG: Подключение к БД",
        "WARN: Мало памяти",
        "DEBUG: Запрос обработан",
        "ERROR: Таймаут соединения",
        "FATAL: Диск полный",
        "INFO: Не должно появиться"
    )

    // TODO: перебери логи с continue для DEBUG и break для FATAL

    val logsMap = logs.map { it.split(": ") }

    for((name, msg) in logsMap) {
        when(name) {
            "DEBUG" -> continue
            "FATAL" -> break
            else -> println("$name: $msg")
        }
    }

    // Ожидаемый вывод:
    // INFO: Сервер запущен
    // WARN: Мало памяти
    // ERROR: Таймаут соединения
}


