/**
 * Задача 5 — Угадай число
 *
 * Симуляция игры "угадай число". Загаданное число — 42.
 * Дан список попыток. Используй while для перебора попыток.
 * Если угадал — выведи "Угадал с N попытки!" и прекрати цикл.
 * Если не угадал — выведи "Попытка N: слишком большое/маленькое".
 */
fun task5() {
    val secret = 42
    val guesses = listOf(10, 50, 30, 42, 99)

    // TODO: используй while (не for!) для перебора попыток
    var counter = 0

    while(true) {
        val currentNumber = guesses[counter]
        if(currentNumber < secret) {
            println("Попытка ${++counter}: $currentNumber - слишком маленькое")
        } else if(currentNumber > secret) {
            println("Попытка ${++counter}: $currentNumber - слишком большое")
        } else {
            println("Попытка ${++counter}: Угадал с $counter попытки!")
            break
        }
    }

    // Ожидаемый вывод:
    // Попытка 1: 10 — слишком маленькое
    // Попытка 2: 50 — слишком большое
    // Попытка 3: 30 — слишком маленькое
    // Попытка 4: Угадал с 4 попытки!
}


