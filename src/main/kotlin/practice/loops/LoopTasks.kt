/**
 * Задача 6 — Бросок кубика
 *
 * Симуляция бросков кубика. Дан список результатов бросков.
 * Используй do-while: бросай пока не выпадет 6.
 * Выведи каждый бросок и итоговое количество бросков.
 */
fun task6() {
    val rolls = listOf(3, 1, 4, 6, 2, 5)

    // TODO: используй do-while для перебора бросков до первой 6

    var counter = 0

    do {
        val currentNumber = rolls[counter]
        if(currentNumber != 6) {
            println("Бросок ${++counter}: $currentNumber")
        } else {
            println("Бросок ${++counter}: $currentNumber - Готово!")
            println("Всего бросков: $counter")
            break
        }
    } while (true)

    // Ожидаемый вывод:
    // Бросок 1: 3
    // Бросок 2: 1
    // Бросок 3: 4
    // Бросок 4: 6 — Готово!
    // Всего бросков: 4
}


